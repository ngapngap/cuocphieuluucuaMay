#!/usr/bin/env python3
"""Build or verify the lossless startup GLBs; never modifies the source GLBs."""
import argparse
import gzip
import json
import re
import struct
import zlib
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
MODELS = ROOT / 'assets' / 'models'


def startup_names():
    source = (ROOT / 'js' / 'packages.js').read_text(encoding='utf-8')
    result = []
    for group in ('common', 'hub'):
        match = re.search(r'\b' + group + r':\s*\[([^\]]*)\]', source)
        if not match:
            raise ValueError('Missing package: ' + group)
        for name in re.findall(r'"([a-zA-Z0-9_-]+)"', match.group(1)):
            if name not in result:
                result.append(name)
    return result


def read_model(path):
    data = path.read_bytes()
    if len(data) < 20:
        raise ValueError('Invalid GLB: ' + str(path))
    magic, version, total, size, chunk = struct.unpack_from('<4sIIII', data)
    if magic != b'glTF' or version != 2 or total != len(data) or chunk != 0x4e4f534a or size > len(data) - 20:
        raise ValueError('Invalid GLB header: ' + str(path))
    model = json.loads(data[20:20 + size])
    for kind in ('buffers', 'images'):
        for item in model.get(kind, []):
            if item.get('uri') and not item['uri'].lower().startswith('data:'):
                raise ValueError('External resource in ' + str(path))
    return data


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true', help='verify generated bytes without writing')
    args = parser.parse_args()
    output = MODELS / 'gzip'
    if not args.check:
        output.mkdir(parents=True, exist_ok=True)
    bad = []
    names = startup_names()
    for name in names:
        source = read_model(MODELS / (name + '.glb'))
        target = output / (name + '.glb.gz')
        if args.check:
            try:
                decoded = gzip.decompress(target.read_bytes())
            except (OSError, EOFError, zlib.error):
                decoded = None
            if decoded != source:
                bad.append(name)
        else:
            encoded = bytearray(gzip.compress(source, compresslevel=9, mtime=0))
            encoded[9] = 255  # Use the platform-independent gzip OS field.
            target.write_bytes(encoded)
    if bad:
        raise SystemExit('Stale or missing gzip models: ' + ', '.join(bad))
    print(('Verified' if args.check else 'Packed') + f' {len(names)} startup models')


if __name__ == '__main__':
    main()
